export function translate(locale, text) {
    if (locale !== "hi" || !text) return text;
    return hindiTranslations[text] || statusTranslations[text] || text;
}

export function translateStatus(locale, status) {
    if (!status) return locale === "hi" ? "अज्ञात" : "Unknown";
    const key = String(status).toUpperCase().replaceAll(" ", "_");
    if (locale === "hi" && statusTranslations[key]) {
        return statusTranslations[key];
    }
    return String(status)
        .toLowerCase()
        .replaceAll("_", " ")
        .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

export function formatLocaleDate(dateValue, locale, options) {
    if (!dateValue) return translate(locale, "Date unavailable");
    const date = new Date(dateValue);
    if (Number.isNaN(date.getTime())) {
        return translate(locale, "Date unavailable");
    }
    return date.toLocaleDateString(locale === "hi" ? "hi-IN" : "en-IN", options);
}

export function LocaleProvider({ children }) {
    const [locale, setLocale] = useState(() =>
        localStorage.getItem("civicos_locale") === "hi" ? "hi" : "en"
    );

    useEffect(() => {
        document.documentElement.lang = locale === "hi" ? "hi" : "en";
        localStorage.setItem("civicos_locale", locale);
    }, [locale]);

    const value = useMemo(
        () => ({
            locale,
            setLocale,
            toggleLocale: () =>
                setLocale((current) => (current === "hi" ? "en" : "hi")),
            t: (text) => translate(locale, text),
        }),
        [locale]
    );

    return (
        <LocaleContext.Provider value={value}>
            {children}
        </LocaleContext.Provider>
    );
}

export function useLocale() {
    const context = useContext(LocaleContext);
    if (!context) {
        throw new Error("useLocale must be used within a LocaleProvider");
    }
    return context;
}
